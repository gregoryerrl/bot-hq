//! migrations seeded.
//!
//! **rc3 D10: nothing here names an agent.** These constants opened with
//! `You are **Brian**` / `You are **Rain**`, and the participant that received
//! them was found by literal slug at spawn. A participant is now named by the
//! ROLE it plays and the MODEL it runs on, so the prose describes the role and
//! layer 6 (below) renders who is actually in the session. The names were the
//! user's to begin with — they can put them back by renaming a role or a model.
//!
//! These are baked into the binary so role identity can't drift if a user
//! edits or deletes a CL file. Each prompt is intentionally short — behaviors
//! that vary by project or user preference belong in
//! `<data_dir>/library/custom-instructions.md` (loaded after this, for every
//! agent).
//!
