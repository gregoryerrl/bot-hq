    /// **rc3 D10's acceptance line, on the bytes an agent actually receives.**
    ///
    /// The user, repeatedly: *"I already said multiple times that I'm dropping
    /// the names, only the Role + Model Name."* Both constants opened with
    /// `You are **Brian**` / `You are **Rain**` and named the other agent by
    /// person-name ~30 times between them.
    ///
    /// Asserted as whole words so `Brianna` or a `--rain` flag would not trip
    /// it, and over BOTH constants so neither can keep a reference to the other.
    #[test]
    fn no_role_prompt_names_an_agent() {
        for (role, name) in [(HANDS_ROLE, "HANDS_ROLE"), (EYES_ROLE, "EYES_ROLE")] {
            for banned in ["Brian", "Rain", "BRAIN"] {
                let hit = role
                    .match_indices(banned)
                    .find(|(i, _)| {
                        let before = role[..*i].chars().next_back();
                        let after = role[i + banned.len()..].chars().next();
                        !before.is_some_and(|c| c.is_ascii_alphanumeric())
                            && !after.is_some_and(|c| c.is_ascii_alphanumeric())
                    });
                assert!(
                    hit.is_none(),
                    "{name} still names an agent: {banned:?} at {:?}",
                    hit.map(|(i, _)| &role[i.saturating_sub(60)..(i + 60).min(role.len())])
                );
            }
        }
        // Non-vacuous: the roles are still named, so the check above is not
        // passing because the constants went empty.
        assert!(HANDS_ROLE.contains("# Role — HANDS"));
        assert!(EYES_ROLE.contains("# Role — EYES"));
    }

